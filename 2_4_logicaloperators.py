a = 10
b = 3

print("a == b, equal to:", a == b)
print("a != b, not equal to:", a != b)
print("a > b, greater than:", a > b)
print("a < b, less than:", a < b)
print("a >= b, greater than or equal to:", a >= b)
print("a <= b, less than or equal to:", a <= b)

print("a > 5 and b > 5, both true:", a > 5 and b > 5)
print("a > 5 or b > 5, at least one true:", a > 5 or b > 5)
print("not a > 5, opposite:", not a > 5)